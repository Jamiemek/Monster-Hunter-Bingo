// variants are added as their own roster entries
function addVariant(game, key, ranks, pick, threat) {
  const wanted = typeof pick === "function" ? pick : (m) => pick.includes(m[0]);
  const base = GAMES[game].monsters.filter((m) => !m[3] && wanted(m));
  for (const m of base) {
    GAMES[game].monsters.push([
      VARIANTS[key] + " " + m[0],
      ranks,
      threat || Math.min(5, m[2] + 1),
      key,
    ]);
  }
}
